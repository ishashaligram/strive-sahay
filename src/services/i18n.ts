const LANG_STORAGE_KEY = 'strive_sahay_user_lang_pref';

export const getSavedLanguage = (): SupportedLanguage => {
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    if (saved && (saved in translations)) {
      return saved as SupportedLanguage;
    }
  } catch {}
  return 'en';
};

export const saveLanguage = (lang: SupportedLanguage): void => {
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch {}
};

export const useTranslation = (lang: SupportedLanguage = 'en') => {
  return translations[lang] || translations.en;
};
